#!/usr/bin/env node
// @ts-check
/**
 * One-click install links for the README (pf-agent-platform-nkwn.35): Cursor, VS Code, VS Code
 * Insiders and LM Studio, all adding the same `npx` server entry.
 *
 *   node scripts/install-links.mjs           print the README block
 *   node scripts/install-links.mjs --write   replace the block between the markers in README.md
 *   node scripts/install-links.mjs --check   exit 1 when README.md's block differs
 *
 * Until `photofresco@<version>` is on npm, SOURCE is 'github': npx installs the package from the
 * GitHub source archive of one public commit (no git, no npm registry). After the npm release set
 * SOURCE to 'npm' and run --write; every link then runs `npx -y photofresco@<version> mcp`.
 *
 * GitHub renders only http(s) links, so the README uses each vendor's web redirect to its deeplink
 * (`cursor://anysphere.cursor-deeplink/mcp/install`, `vscode:mcp/install`, `lmstudio://add_mcp`);
 * `deeplinks()` returns the deeplinks themselves.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const README = fileURLToPath(new URL('../README.md', import.meta.url))
const PACKAGE = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))

/** 'github' until the npm package is published (pf-agent-platform-nkwn.39), then 'npm'. */
export const SOURCE = /** @type {'github' | 'npm'} */ ('github')
/** A public commit of photofresco/photofresco-agent whose package.json version is the package version. */
export const GITHUB_COMMIT = '328cfaf3caf6483c5660381f19f2afdb2059a215'
export const REPO = 'https://github.com/photofresco/photofresco-agent'
export const NAME = 'photofresco'
export const START = '<!-- install-links:start (generated by scripts/install-links.mjs; edit it there) -->'
export const END = '<!-- install-links:end -->'

/** @param {'github' | 'npm'} [source] */
export function npxArgs(source = SOURCE) {
  return source === 'npm'
    ? ['-y', `${PACKAGE.name}@${PACKAGE.version}`, 'mcp']
    : ['-y', `--package=${REPO}/archive/${GITHUB_COMMIT}.tar.gz`, PACKAGE.name, 'mcp']
}

/** The server entry every link adds: no folders granted, as with a plugin install. @param {'github' | 'npm'} [source] */
export const serverConfig = (source = SOURCE) => ({ command: 'npx', args: npxArgs(source) })

const base64 = (/** @type {object} */ value) => encodeURIComponent(Buffer.from(JSON.stringify(value)).toString('base64'))

/** The clients' own URL schemes. @param {'github' | 'npm'} [source] */
export function deeplinks(source = SOURCE) {
  const config = serverConfig(source)
  return {
    cursor: `cursor://anysphere.cursor-deeplink/mcp/install?name=${NAME}&config=${base64(config)}`,
    vscode: `vscode:mcp/install?${encodeURIComponent(JSON.stringify({ name: NAME, type: 'stdio', ...config }))}`,
    vscodeInsiders: `vscode-insiders:mcp/install?${encodeURIComponent(JSON.stringify({ name: NAME, type: 'stdio', ...config }))}`,
    lmstudio: `lmstudio://add_mcp?name=${NAME}&config=${base64(config)}`,
  }
}

/** The https pages that open those deeplinks (what the README links). @param {'github' | 'npm'} [source] */
export function webLinks(source = SOURCE) {
  const config = serverConfig(source)
  const vscode = `https://vscode.dev/redirect/mcp/install?name=${NAME}&config=${encodeURIComponent(JSON.stringify({ type: 'stdio', ...config }))}`
  return {
    cursor: `https://cursor.com/en/install-mcp?name=${NAME}&config=${base64(config)}`,
    vscode,
    vscodeInsiders: `${vscode}&quality=insiders`,
    lmstudio: `https://lmstudio.ai/install-mcp?name=${NAME}&config=${base64(config)}`,
  }
}

/** The README block between START and END. @param {'github' | 'npm'} [source] */
export function readmeBlock(source = SOURCE) {
  const links = webLinks(source)
  const from = source === 'npm'
    ? `\`npx -y ${PACKAGE.name}@${PACKAGE.version} mcp\``
    : `\`npx\` from the GitHub source archive of version ${PACKAGE.version} (commit \`${GITHUB_COMMIT.slice(0, 7)}\`; nothing comes from the npm registry)`
  return [
    START,
    `[![Add to Cursor](https://cursor.com/deeplink/mcp-install-dark.svg)](${links.cursor})`,
    `[![Install in VS Code](https://img.shields.io/badge/VS_Code-Install_PhotoFresco-0098FF?logo=visualstudiocode&logoColor=white)](${links.vscode})`,
    `[![Install in VS Code Insiders](https://img.shields.io/badge/VS_Code_Insiders-Install_PhotoFresco-24bfa5?logo=visualstudiocode&logoColor=white)](${links.vscodeInsiders})`,
    `[![Add to LM Studio](https://files.lmstudio.ai/deeplink/mcp-install-dark.svg)](${links.lmstudio})`,
    '',
    `Each button asks the app to add the \`${NAME}\` server, started with`,
    `${from}. It grants no folders: add \`--read\` and \`--write\` arguments after \`mcp\` in the app's MCP`,
    'settings to let the agent open and save files.',
    END,
  ].join('\n')
}

/** README text with the block replaced. @param {string} text @param {'github' | 'npm'} [source] */
export function withBlock(text, source = SOURCE) {
  const start = text.indexOf(START)
  const end = text.indexOf(END)
  if (start < 0 || end < start) throw new Error(`README.md has no ${START} … ${END} block`)
  return text.slice(0, start) + readmeBlock(source) + text.slice(end + END.length)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const mode = process.argv[2]
  if (mode === '--write' || mode === '--check') {
    const text = readFileSync(README, 'utf8')
    const next = withBlock(text)
    if (mode === '--write') writeFileSync(README, next)
    else if (next !== text) {
      process.stderr.write('README.md install links are out of date: run node scripts/install-links.mjs --write\n')
      process.exitCode = 1
    }
  } else if (mode === undefined) {
    process.stdout.write(`${readmeBlock()}\n`)
  } else {
    process.stderr.write('Usage: node scripts/install-links.mjs [--write | --check]\n')
    process.exitCode = 2
  }
}
