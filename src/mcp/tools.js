// @ts-check
import { readdirSync, readFileSync } from 'node:fs'

/**
 * MCP tool definitions for PhotoFresco (pf-agent-platform-nkwn.15): op tools derived from the
 * operation catalog (one MCP tool per editor operation, no generic executor), the session
 * lifecycle tools, op groups for clients with tool-count limits, and the one mapping from
 * OpMetadata effects to MCP tool annotations.
 *
 * Before a session exists the server lists the bundled catalog: catalog/<namespace>.json, one file
 * per op namespace so every file stays under the 256 KiB per-file cap of plugin directories, a
 * snapshot of a fully granted session's operations() regenerated by
 * test/agent-mcp-catalog.test.mjs in the editor repository. Once paired it lists the live
 * operations() the user's grants allow. Listing is documentation, not authority: the editor
 * enforces grants on every call.
 *
 * @typedef {'read' | 'document' | 'view' | 'local-storage' | 'external-write' | 'paid' | 'lifecycle'} Effect
 * @typedef {'read' | 'edit' | 'export' | 'spend' | 'external-write'} Capability
 * @typedef {object} Operation One entry of operations() (and of the bundled catalog).
 * @property {string} name Canonical op name (`layer.add`).
 * @property {string} tool_name Model-safe name (`layer_add`); never derived by replacing underscores.
 * @property {string} description
 * @property {ObjectSchema} input_schema
 * @property {Effect[]} effects
 * @property {Capability[]} capabilities
 * @property {'sync' | 'async'} completion
 *
 * @typedef {{ readOnlyHint: boolean, destructiveHint: boolean, idempotentHint: boolean, openWorldHint: boolean }} ToolAnnotations
 * @typedef {{ type: 'object' } & Record<string, any>} ObjectSchema
 * @typedef {{ name: string, title: string, description: string, inputSchema: ObjectSchema, annotations: ToolAnnotations }} ToolDefinition
 */

const CATALOG_DIR = new URL('./catalog/', import.meta.url)

/** @returns {{ operations: Operation[] }} The bundled catalog, sorted by op name. */
export function loadCatalog() {
  const files = readdirSync(CATALOG_DIR).filter((file) => file.endsWith('.json')).sort()
  /** @type {Operation[]} */
  const operations = files.flatMap((file) => JSON.parse(readFileSync(new URL(file, CATALOG_DIR), 'utf8')).operations)
  return { operations: operations.sort((a, b) => a.name.localeCompare(b.name)) }
}

// ---- annotations -----------------------------------------------------------------------

/** Effects that cannot be taken back with history_undo and change or lose data outside the open document's history. */
const DESTRUCTIVE_EFFECTS = Object.freeze({ lifecycle: true, 'local-storage': true, 'external-write': true, paid: true })

/**
 * The one mapping from OpMetadata to MCP annotations:
 * - readOnlyHint only when every effect is `read`;
 * - destructiveHint for lifecycle (tabs opened/closed/replaced), local-storage, external-write and
 *   paid effects, which history_undo does not revert. Undoable document edits and view/tool
 *   settings are not destructive;
 * - openWorldHint for effects that reach PhotoFresco services (external-write, paid);
 * - idempotentHint only for read-only operations (repeating a read changes nothing). No editing
 *   operation is claimed idempotent.
 * @param {{ effects: readonly string[] }} metadata
 * @returns {ToolAnnotations}
 */
export function annotationsFor(metadata) {
  const readOnly = metadata.effects.length > 0 && metadata.effects.every((effect) => effect === 'read')
  return {
    readOnlyHint: readOnly,
    destructiveHint: !readOnly && metadata.effects.some((effect) => Object.hasOwn(DESTRUCTIVE_EFFECTS, effect)),
    idempotentHint: readOnly,
    openWorldHint: metadata.effects.some((effect) => effect === 'external-write' || effect === 'paid'),
  }
}

