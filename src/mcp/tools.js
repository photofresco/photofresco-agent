/** @type {Readonly<Record<string, string>>} Title nouns where capitalizing the prefix reads wrong. */
const PREFIX_LABELS = Object.freeze({
  doc: 'Document', adjust: 'Adjustment', ai: 'AI', ui: 'Editor', smart: 'Smart object', quickmask: 'Quick mask',
  dock: 'Panels', heal: 'Healing', clone: 'Clone stamp', bucket: 'Paint bucket', erase: 'Eraser', render: 'Preview',
  drive: 'My Documents', style: 'Layer style',
})

/** @param {string} words */
const sentence = (words) => words.charAt(0).toUpperCase() + words.slice(1).replace(/_/g, ' ')

/** `layer.set_fill_opacity` → `Layer: Set fill opacity`. @param {string} opName */
export function titleFor(opName) {
  const dot = opName.indexOf('.')
  const prefix = opName.slice(0, dot)
  const label = Object.hasOwn(PREFIX_LABELS, prefix) ? PREFIX_LABELS[prefix] : sentence(prefix)
  return `${label}: ${sentence(opName.slice(dot + 1))}`
}

const EFFECT_TEXT = Object.freeze({
  read: 'Reads the document or editor state; changes nothing.',
  document: 'Edits the document through an undoable command that appears in History.',
  view: 'Changes editor view or tool settings; not a document edit and not in History.',
  lifecycle: 'Opens, closes, duplicates or reverts documents (tabs); history_undo does not reverse it.',
  'local-storage': 'Writes browser storage (actions, presets, autosave or My Documents); history_undo does not reverse it.',
  'external-write': 'Sends document data to PhotoFresco services.',
  paid: 'Spends AI credits from the budget the user granted; credits are not refunded once the provider starts.',
})

const CAPABILITY_LABELS = Object.freeze({ read: 'Read', edit: 'Edit', export: 'Export', 'external-write': 'Send', spend: 'Spend' })

/** @type {Readonly<Record<string, string>>} Pointers to the better tool for a few operations. */
const SEE_ALSO = Object.freeze({
  'doc.open': 'For a file on this computer use photofresco_import_file instead of passing base64.',
  'export.artifact': 'The result links an MCP resource (photofresco://artifact/<id>) holding the bytes; photofresco_export_file writes the export to a granted folder in one step.',
  'artifact.read': 'Prefer reading the photofresco://artifact/<id> resource, which assembles and verifies the chunks.',
  'history.undo': 'Reverts the last History entry, including edits made by the user.',
})

/** @param {Effect[]} effects */
function undoText(effects) {
  if (effects.every((effect) => effect === 'read' || effect === 'view')) return ''
  if (effects.every((effect) => effect === 'document')) return 'Undo: history_undo reverts it.'
  if (effects.includes('document')) return 'Undo: history_undo reverts the document edit, not the other effects.'
  return 'Undo: not reversible with history_undo.'
}

/** @param {Record<string, any>} schema */
function inputsText(schema) {
  const names = Object.keys(schema.properties ?? {})
  if (!names.length) return 'Inputs: none.'
  const required = new Set(schema.required ?? [])
  return `Inputs: ${names.map((name) => (required.has(name) ? `${name} (required)` : name)).join(', ')}. Units, ranges and allowed values are in the input schema; the editor rejects arguments outside it before anything runs.`
}

/**
 * The full description an MCP client and model see: what the op does, its inputs, effect, undo
 * behaviour, the user permission it needs and when it completes.
 * @param {Operation} op
 */
export function describeOperation(op) {
  const lines = [op.description.trim(), '']
  if (Object.hasOwn(SEE_ALSO, op.name)) lines.push(SEE_ALSO[op.name])
  lines.push(inputsText(op.input_schema))
  lines.push(`Effect: ${op.effects.map((effect) => EFFECT_TEXT[effect] ?? effect).join(' ')}`)
  if (!op.name.startsWith('history.')) {
    const undo = undoText(op.effects)
    if (undo) lines.push(undo)
  }
  const permissions = op.capabilities.map((capability) => CAPABILITY_LABELS[capability] ?? capability).join(' + ')
  lines.push(`Permission: ${permissions}, granted by the user in the PhotoFresco window (ask with photofresco_request_access).`)
  lines.push(op.completion === 'async' ? 'Returns when the operation has finished (it may take seconds).' : 'Returns immediately with the result.')
  lines.push(`Results carry document_id and revision. PhotoFresco operation: ${op.name}.`)
  return lines.filter((line, index) => line !== '' || index === 1).join('\n')
}

/** @param {Operation} op @returns {ToolDefinition} */
export function operationTool(op) {
  return {
    name: op.tool_name,
    title: titleFor(op.name),
    description: describeOperation(op),
    inputSchema: op.input_schema,
    annotations: annotationsFor(op),
  }
}

