export const DEFAULT_TOOL_GROUPS = Object.freeze(['essentials'])

/** @type {Readonly<Record<string, string>>} */
const GROUP_BY_PREFIX = Object.freeze(Object.fromEntries(
  Object.entries(TOOL_GROUPS).flatMap(([group, spec]) => (spec.prefixes ?? []).map((prefix) => [prefix, group])),
))

/** @param {string} opName @returns {string} The topical group of a canonical op name. */
export function groupOf(opName) {
  const prefix = opName.slice(0, opName.indexOf('.'))
  return Object.hasOwn(GROUP_BY_PREFIX, prefix) ? GROUP_BY_PREFIX[prefix] : 'other'
}

/**
 * Parse a `--tools` value: `all`, or comma-separated group IDs.
 * @param {string | undefined} value
 * @returns {string[]}
 */
export function parseToolGroups(value) {
  if (value === undefined || value.trim() === '') return [...DEFAULT_TOOL_GROUPS]
  const ids = value.split(',').map((id) => id.trim()).filter(Boolean)
  if (ids.includes('all')) return Object.keys(TOOL_GROUPS)
  const unknown = ids.filter((id) => !Object.hasOwn(TOOL_GROUPS, id))
  if (unknown.length) throw new Error(`Unknown tool group ${unknown.join(', ')}; use all or ${Object.keys(TOOL_GROUPS).join(', ')}`)
  return ids
}

/** @param {ReadonlySet<string>} enabled @param {string} opName */
export function groupEnabled(enabled, opName) {
  return enabled.has(groupOf(opName)) || (enabled.has('essentials') && /** @type {readonly string[]} */ (TOOL_GROUPS.essentials.ops).includes(opName))
}

